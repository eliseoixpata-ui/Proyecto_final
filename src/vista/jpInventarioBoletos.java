private void cargarConciertos(){
    listaConciertos = conciertoDao.listar();
    cmbxConcierto.removeAllItems();
    for (Concierto c : listaConciertos){
        cmbxConcierto.addItem(c.getTituloEvento());
    }
}

private void cargarLocalidades(){
    listaLocalidades = localidadesDao.listar();
    cmbxLocalidad.removeAllItems();
    for (Localidad l : listaLocalidades){
        cmbxLocalidad.addItem(l.getNombre());
    }
}

private void cargarTabla(){
    DefaultTableModel modelo = new DefaultTableModel(
            new Object[]{"ID", "Concierto", "Localidad", "Precio", "Total", "Disponible."}, 0){
        @Override
        public boolean isCellEditable(int fila, int columna) {
            return false;
        }
                
    }; 
    for (InventarioBoleto inv : inventarioController.listar()){
        
        String nombreConcierto = "";
        for (Concierto c : listaConciertos) {
            if (c.getIdConcierto() == inv.getIdConcierto()){
                nombreConcierto = c.getTituloEvento();
                break;
            }
        }
        
        String nombreLocalidad = "";
        for (Localidad l : listaLocalidades){
            if (l.getIdLocalidad() == inv.getIdLocalidad()){
                nombreLocalidad = l.getNombre();
                break;
            }
        }
        
        modelo.addRow(new Object[]{
            inv.getIdInventario(),
            nombreConcierto,
            nombreLocalidad,
            inv.getPrecio(),
            inv.getCantidadTotal(),
            inv.getCantidadDisponible()
        });
    }
    
    tblInventario.setModel(modelo);

}

private void limpiarCampos(){
    txtID.setText("");
    txtPrecio.setText("");
    txtCantidadTotal.setText("");
    txtCantidadDisponible.setText("");
    if (cmbxConcierto.getItemCount() > 0) {
        cmbxConcierto.setSelectedIndex(0);
    }
    if (cmbxLocalidad.getItemCount() > 0){
        cmbxLocalidad.setSelectedIndex(0);
        
    }
}

private InventarioBoleto leerFormulario(){
    InventarioBoleto inv = new InventarioBoleto();
    inv.setIdConcierto(listaConciertos.get(cmbxConcierto.getSelectedIndex()).getIdConcierto());
    inv.setIdLocalidad(listaLocalidades.get(cmbxLocalidad.getSelectedIndex()).getIdLocalidad());
    inv.setPrecio(Double.parseDouble(txtPrecio.getText().trim()));
    inv.setCantidadTotal(Integer.parseInt(txtCantidadTotal.getText().trim()));
    inv.setCantidadDisponible(Integer.parseInt(txtCantidadDisponible.getText().trim()));
    return inv;
    
}
