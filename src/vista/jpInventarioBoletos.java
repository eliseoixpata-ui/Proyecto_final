    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        if (cmbxConcierto.getSelectedIndex() == .1 || cmbxLocalidad.getSelectedIndex()== -1) {
            JOptionPane.showMessageDialog(this, "Seleccione un concierto y una localidad");
            return;
            
        }
        try {
            InventarioBoleto inventario = leerFormulario();
            
            if (inventario.getCantidadDisponible()> inventario.getCantidadTotal()){
                JOptionPane.showMessageDialog(this, "La cantidad disponible no puede ser mayor que la total");
                return;
            }
            
            if (inventarioController.insertar(inventario)){
                JOptionPane.showMessageDialog(this, "Inventario guardado correctamente");
                limpiarCampos();
                cargarTabla();
            } else {
                JOptionPane.showMessageDialog(this, "Error al guardar inventario");
            }
            
        } catch (NumberFormatException ex){
            JOptionPane.showConfirmDialog(this, "Precio y cantidades deben ser numericos");
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        if (txtID.getText().isEmpty()){
            JOptionPane.showMessageDialog(this, "Seleccione un registro de la tabla");
            return;
            
        }
        if (cmbxConcierto.getSelectedIndex()== -1 || cmbxLocalidad.getSelectedIndex()==-1){
            JOptionPane.showMessageDialog(this, "Seleccione un concierto y una localidad");
            return;
        }
        
        try {
            InventarioBoleto inventario = leerFormulario();
            inventario.setIdInventario(Integer.parseInt(txtID.getText()));
            
            if (inventario.getCantidadDisponible()> inventario.getCantidadTotal()){
                JOptionPane.showMessageDialog(this, "La cantidad disponible no puede ser mayor que la total");
                limpiarCampos();
                cargarTabla();
            } else {
                JOptionPane.showMessageDialog(this, "Error al actualizar el inventario");
                
            }
            
        } catch(NumberFormatException ex){
            JOptionPane.showMessageDialog(this, "Precio y cantidades deben numericos");
            
        }
        
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        if (txtID.getText().isEmpty()){
            JOptionPane.showMessageDialog(this, "Seleccione un regidtro de la tabla");
            return;
        }
        int respuesta = JOptionPane.showConfirmDialog(
                this,
                "¿Desea eliminar este registro de inventario?",
                "Confirmar",
                JOptionPane.YES_NO_OPTION
        );
        if (respuesta == JOptionPane.YES_OPTION){
            int id = Integer.parseInt(txtID.getText());
            
            if (inventarioController.eliminar(id)){
                JOptionPane.showMessageDialog(this, "Inventario eliminado correctamente");
                limpiarCampos();
                cargarTabla();
            } else {
                JOptionPane.showMessageDialog(this, "No se pudo eliminar el inventario");
            }
        }
        
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void tblInventarioMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblInventarioMouseClicked
        int fila = tblInventario.getSelectedRow();
        
        if (fila == -1){
            return;
        }
        
        txtID.setText(tblInventario.getValueAt(fila, 0).toString());
        cmbxConcierto.setSelectedItem(tblInventario.getValueAt(fila, 1).toString());
        cmbxLocalidad.setSelectedItem(tblInventario.getValueAt(fila, 2).toString());
        txtPrecio.setText(tblInventario.getValueAt(fila, 3).toString());
        txtCantidadTotal.setText(tblInventario.getValueAt(fila, 4).toString());
        txtCantidadDisponible.setText(tblInventario.getValueAt(fila, 5).toString());
    }//GEN-LAST:event_tblInventarioMouseClicked


