    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        if (cmbxConcierto.getSelectedIndex() == -1 || cmbxLocalidad.getSelectedIndex() == -1){
            JOptionPane.showMessageDialog(this, "Seleccione un concierto y una localidad");
            return;
        }
        Concierto concierto = listaConciertos.get(cmbxConcierto.getSelectedIndex());
        Localidad localidad = listaLocalidades.get(cmbxLocalidad.getSelectedIndex());
        int cantidad = ((Number) spnCantidad.getValue()).intValue();
        
        InventarioBoleto inv = buscarInventario(concierto.getIdConcierto(), localidad.getIdLocalidad());
        if (inv == null) {
            JOptionPane.showMessageDialog(this, "No hay inventario de boletos para ese concierto y localidad");
            return;
        }
        int yaAgregados = cantidadYaAgregada(inv.getIdInventario());
        
        if (cantidad + yaAgregados > inv.getCantidadDisponible()) {
            JOptionPane.showMessageDialog(this, "Solo hay" + inv.getCantidadDisponible() + "boletos disponibles");
            return;
        }
        DetalleVenta detalle = new DetalleVenta();
        detalle.setIdInventario(inv.getIdInventario());
        detalle.setCantidad(cantidad);
        detalle.setPrecioUnitario(inv.getPrecio());
        detalle.setSubtotal(cantidad * inv.getPrecio());
        detalles.add(detalle);
        
        modeloDetalle.addRow(new Object[]{
            detalles.size(),
            concierto.getTituloEvento(),
            localidad.getNombre(),
            cantidad,
            inv.getPrecio(),
            detalle.getSubtotal()
        });
        
        total = total + detalle.getSubtotal();
        actualizarTotal();
        

    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        if (cmbxVendedor.getSelectedIndex() == -1){
            JOptionPane.showMessageDialog(this, "Seleccione un vendedor");
            return;
        }
        
        if (detalles.isEmpty()){
            JOptionPane.showMessageDialog(this, "Agrefue al menos un boleto a la venta");
            return;
        }
        Venta venta = new Venta();
        venta.setIdVendedor(listaVendedores.get(cmbxVendedor.getSelectedIndex()).getIdUsuario());
        venta.setTotalVenta(total);
        
        if (ventaController.registrarVenta(venta, detalles)){
            JOptionPane.showMessageDialog(this, "Vemta registrada correctamente por  Q " + String.format("%.2f", total));
            limpiarVenta();
            
        } else {
            JOptionPane.showMessageDialog(this, "No se pudo registrar la venta. Revise que haya boletos disponibles");
        }
        
    }//GEN-LAST:event_btnGuardarActionPerformed


