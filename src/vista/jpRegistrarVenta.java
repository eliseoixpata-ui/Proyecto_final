private void cargarVendedores(){
    listaVendedores = usuarioDao.listar();
    cmbxVendedor.removeAllItems();
    for (usuarios u : listaVendedores) {
        cmbxVendedor.addItem(u.getNombreCompleto());
    }
}
    
private void cargarConciertos(){
    listaConciertos = conciertoDao.listar();
    cmbxConcierto.removeAllItems();
    for (Concierto c : listaConciertos){
        cmbxConcierto.addItem(c.getTituloEvento());
    }
}
    
private void cargarLocalidades(){
    listaLocalidades = localidadesDao.listar();
    cmbxLocalidad.removeAllItems();
    for (Localidad l : listaLocalidades){
        cmbxLocalidad.addItem(l.getNombre());
    }
    
}
    
private void prepararTabla(){
    modeloDetalle = new DefaultTableModel(
            new Object[]{"#", "Concierto", "Localidad", "Cantidad", "Precio", "Subtotal"}, 0){
        @Override
        public boolean isCellEditable(int fila, int columna){
            return false;
        }
        
    };
    tblDetalle.setModel(modeloDetalle);
    
}
    
private void actualizarTotal(){
    lblTotal.setText("Q " + String.format("%.2f", total));
    
}
private InventarioBoleto buscarInventario(int idConcierto, int idLocalidad){
    for (InventarioBoleto inv : inventarioController.listarPorConcierto(idConcierto)){
        if (inv.getIdLocalidad()== idLocalidad){
             return inv;
        }     
    }
    return null;
}
private int cantidadYaAgregada(int idInventario){
    int suma = 0;
    for (DetalleVenta d : detalles){
        if (d.getIdInventario() == idInventario){
            suma = suma + d.getCantidad();
        }
    }
    return suma;
}
private void limpiarVenta(){
    detalles.clear();
    modeloDetalle.setRowCount(0);
    total = 0;
    actualizarTotal();
    spnCantidad.setValue(1);
    if (cmbxConcierto.getItemCount() > 0) {
        cmbxConcierto.setSelectedIndex(0);
    }
    if (cmbxLocalidad.getItemCount() > 0) {
        cmbxLocalidad.setSelectedIndex(0);
    }
}
    
