    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        if ( txtNombre.getText().trim().isEmpty()){
            JOptionPane.showMessageDialog(this, "Ingrese el nombre de la localidad");
            return ;
        }
        Localidad localidad =  new Localidad();
        localidad.setNombre(txtNombre.getText().trim());
        boolean resultado = localidadController.guardar(localidad);
        
        if (resultado){
            JOptionPane.showMessageDialog(this , "Localidad guardada correctamente");
            limpiarCampos();
            cargarTabla();
        }else{
            JOptionPane.showMessageDialog(this, "NO se pudo guardar la localidad");
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

