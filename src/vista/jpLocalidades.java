    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        if (txtID.getText().isEmpty()){
            JOptionPane.showMessageDialog(this, "Seleccione una Localidad");
            return; 
        }
        if (txtNombre.getText().isEmpty()){
            JOptionPane.showMessageDialog(this, "Ingrese el Nombre de la localidad");
            return; 
        }
        if (txtID.getText().equals("Automático")) {
            JOptionPane.showMessageDialog(this, "Seleccione una localidad");
            return;
        }
        Localidad localidad = new Localidad();
        
        localidad.setIdLocalidad(Integer.parseInt(txtID.getText()));
        
        localidad.setNombre(txtNombre.getText().trim());
        boolean resultado = localidadController.actualizar(localidad);
        
        if ( resultado){
            JOptionPane.showMessageDialog(this, " Localidad actualizada correctamente");
            limpiarCampos();
            cargarTabla();
        }else{
            JOptionPane.showMessageDialog(this , " NO se pudo actualizar");
        }
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
       if (txtID.getText().isEmpty()){
           JOptionPane.showMessageDialog(this, " Seleccione una Localidad");
           return; 
       }
       if (txtID.getText().equals("Automático")) {
            JOptionPane.showMessageDialog(this, "Seleccione una localidad");
            return;
        }
       int respuesta = JOptionPane.showConfirmDialog(
            this,
            "¿Desea eliminar esta localidad?",
            "Confirmar",
            JOptionPane.YES_NO_OPTION);
       if ( respuesta == JOptionPane.YES_OPTION){
           int id = Integer.parseInt(txtID.getText());
           boolean resultado = localidadController.eliminar(id);
           
           if(resultado){
               JOptionPane.showMessageDialog(this, "Localidad Eliminada Correctamente");
               limpiarCampos();
               cargarTabla();
           }else{
               JOptionPane.showMessageDialog(this, "No se pudo eliminar la localidad");
           }                             
       }             
    }//GEN-LAST:event_btnEliminarActionPerformed

